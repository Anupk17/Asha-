/**
 * Seeds the database for the given user with 8 synthetic beneficiaries,
 * 20 past visits, and follow-ups.
 */
export async function seedDatabase(uid: string): Promise<{ beneficiaries: number; visits: number; followups: number }> {
  console.info(`🌱 Seeding synthetic data for user: ${uid}...`);

  for (const b of SYNTHETIC_BENEFICIARIES) {
    await saveBeneficiary(uid, b);
  }

  for (const v of SYNTHETIC_VISITS) {
    await saveVisit(uid, v);
  }

  for (const f of SYNTHETIC_FOLLOWUPS) {
    await saveFollowUp(uid, f);
  }

  await logAuditEvent(uid, 'database_seeded', {
    beneficiaries_count: SYNTHETIC_BENEFICIARIES.length,
    visits_count: SYNTHETIC_VISITS.length,
    followups_count: SYNTHETIC_FOLLOWUPS.length,
    notice: 'All seeded records are synthetic',
  });

  return {
    beneficiaries: SYNTHETIC_BENEFICIARIES.length,
    visits: SYNTHETIC_VISITS.length,
    followups: SYNTHETIC_FOLLOWUPS.length,
  };
}

